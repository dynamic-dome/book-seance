def voice(id, name, role, persona, quote, aliases=(), own=None, **theme):
    return {
        "own": own,
        "id": id,
        "name": name,
        "role": role,
        "persona": persona,
        "refusal": "I did not know that at the time.",
        "aliases": list(aliases),
        "quote": quote,
        "theme": theme,
    }


